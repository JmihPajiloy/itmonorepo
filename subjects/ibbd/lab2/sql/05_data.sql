DO $$
DECLARE
  t record;
BEGIN
  FOR t IN SELECT * FROM (VALUES
      ('customer', 'customer_id'),
      ('instrument_type', 'type_id'),
      ('instrument', 'instrument_id'),
      ('employee', 'employee_id'),
      ('service', 'service_id'),
