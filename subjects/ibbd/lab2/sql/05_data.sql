      ('inspection', 'inspection_id'),
      ('payment', 'payment_id')
  ) AS v(tab, col) LOOP
    EXECUTE format(
      'SELECT setval(pg_get_serial_sequence(%L, %L), '
      '(SELECT max(%I) FROM %I))',
      t.tab, t.col, t.col, t.tab);
  END LOOP;
END $$;

COMMIT;
